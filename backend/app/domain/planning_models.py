"""Domain contracts shared by creation, comparison and revision workflows."""
from __future__ import annotations

from datetime import date as CalendarDate
from typing import Any, Literal
from uuid import uuid4

from pydantic import BaseModel, Field, field_validator

from backend.app.domain.field_validation import normalize_trip_fields
from backend.app.domain.place_models import Place


def new_id() -> str:
    return str(uuid4())


class TripConstraints(BaseModel):
    destination: str | None = None
    origin_city: str | None = None
    date_range: str | None = None
    start_date: CalendarDate | None = None
    trip_length: int | None = Field(default=None, gt=0, le=30)
    budget: int | None = Field(default=None, gt=0)
    interests: list[str] = Field(default_factory=list)
    transport_preference: Literal["train", "flight", "bus", "car", "mixed", "any"] | None = None
    physical_level: Literal["low", "medium", "high"] | None = None
    home_currency: str = "CNY"
    taste_profile: str = ""

    @field_validator("destination", "origin_city")
    @classmethod
    def canonical_city(cls, value):
        if value:
            from backend.app.domain.destination_names import canonical_destination
            return canonical_destination(value)
        return value

    @classmethod
    def from_fields(cls, fields: dict[str, Any]):
        values = normalize_trip_fields(fields)
        return cls.model_validate({k: v for k, v in values.items() if k in cls.model_fields})


class Activity(BaseModel):
    activity_id: str = Field(default_factory=new_id)
    title: str
    description: str = ""
    category: str = "general"
    time_slot: Literal["morning", "afternoon", "evening", "flexible"] = "flexible"
    display_time_slot: str | None = None
    place_id: str | None = None
    places: list[Place] = Field(default_factory=list)
    place_resolution: Literal["unattempted", "resolved", "ambiguous", "not_found", "not_applicable", "error"] = "unattempted"
    place_resolution_reason: str = ""
    duration_minutes: int | None = Field(default=None, gt=0)
    estimated_cost: float | None = Field(default=None, ge=0)
    evidence_ids: list[str] = Field(default_factory=list)
    status: Literal["proposed", "confirmed", "needs_verification"] = "needs_verification"


class Day(BaseModel):
    day_id: str = Field(default_factory=new_id)
    day: int = Field(gt=0)
    date: CalendarDate | None = None
    destination: str
    activities: list[Activity] = Field(default_factory=list)
    plan: str = ""  # Compatibility view generated by plan_renderer, not editable business state.


class ValidationIssue(BaseModel):
    code: str
    severity: Literal["error", "warning"]
    message: str
    target_id: str | None = None


class AffectedScope(BaseModel):
    day_numbers: list[int] = Field(default_factory=list)
    activity_ids: list[str] = Field(default_factory=list)
    preserve_activity_ids: list[str] = Field(default_factory=list)
    full_replan: bool = False
    reasons: list[str] = Field(default_factory=list)


class RevisionChange(BaseModel):
    action: Literal["replace", "remove", "relax", "add"] = "replace"
    activity_ids: list[str] = Field(default_factory=list)
    day_numbers: list[int] = Field(default_factory=list)
    time_slot: Literal["morning", "afternoon", "evening", "flexible"] | None = None
    requirements: str = ""
    category: str | None = None


class RevisionRequest(BaseModel):
    base_plan_id: str | None = None
    base_version: int | None = Field(default=None, gt=0)
    changes: list[RevisionChange] = Field(default_factory=list)
    preserve_activity_ids: list[str] = Field(default_factory=list)
    constraints_updates: dict[str, Any] = Field(default_factory=dict)

    @field_validator("constraints_updates")
    @classmethod
    def validate_updates(cls, value):
        unknown = set(value) - set(TripConstraints.model_fields)
        if unknown:
            raise ValueError(f"Unsupported constraint fields: {sorted(unknown)}")
        values = normalize_trip_fields(value)
        validated = TripConstraints.model_validate(values)
        return {k: getattr(validated, k) for k in value}


class PlanningTask(BaseModel):
    task_id: str = Field(default_factory=new_id)
    operation: Literal["create", "revise"] = "create"
    constraints: TripConstraints
    candidate_destinations: list[str] = Field(default_factory=list)
    rejected_destinations: list[str] = Field(default_factory=list)
    requested_output: Literal["options", "itinerary"] = "itinerary"
    response_language: str = "en"
    queries: list[str] = Field(default_factory=list)
    user_message: str = ""
    revision: RevisionRequest | None = None
    affected_scope: AffectedScope | None = None
